"""Build a customer host's .env for the self-contained stack (deploy/customer/compose.yaml, R8.1).

Runs inside the approved image (scripts/customer/ceph-ai-customer.sh), so the set of
keys it may write is exactly what that image's Settings accepts (extra="forbid": an
unknown key would crash-loop every container).

    python scripts/customer/build_env.py --out /var/lib/ceph-ai/config/.env [--old-env OLD] < secrets.json

secrets.json (stdin, never argv): {"db_password", "rabbitmq_password", "session_secret",
"dashboard_password_hash"}. Prints only key names: what was carried over from the old
file, what was dropped and why.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

from dotenv import dotenv_values

# Owned by the new stack: never taken from an old install.
REPLACED = frozenset({
    "DATABASE_URL", "RABBITMQ_URL", "SESSION_SECRET_KEY", "DASHBOARD_PASSWORD_HASH",
    "SSH_KEY_PATH", "AUTOPILOT_ENABLED", "CEPH_AI_ENVIRONMENT", "TELEGRAM_LISTENER_ENABLED",
})
# Point at systems an old install used and the new one must not reach on its own.
DROPPED = frozenset({"TELEGRAM_FEDERATED_DATABASE_URLS"})
_SECRET_KEYS = ("db_password", "rabbitmq_password", "session_secret", "dashboard_password_hash")


def allowed_keys() -> set[str]:
    from config.settings import Settings
    return {name.upper() for name in Settings.model_fields}


def build(old: dict[str, str | None], secrets: dict[str, str], allowed: set[str]) -> tuple[dict[str, str], dict]:
    missing = [key for key in _SECRET_KEYS if not secrets.get(key)]
    if missing:
        raise ValueError(f"missing secrets: {', '.join(missing)}")
    values: dict[str, str] = {}
    report: dict[str, list[str]] = {"carried": [], "replaced": [], "dropped_unknown": [], "dropped_on_purpose": []}
    for key, value in old.items():
        if value is None:
            continue
        if key in REPLACED:
            report["replaced"].append(key)
        elif key in DROPPED or key.startswith("FEDERATION_"):
            report["dropped_on_purpose"].append(key)
        elif key not in allowed:
            report["dropped_unknown"].append(key)
        else:
            values[key] = value
            report["carried"].append(key)
    values.update({
        "DATABASE_URL": f"postgresql+psycopg://ceph_ai:{secrets['db_password']}@postgres:5432/ceph_ai",
        "RABBITMQ_URL": f"amqp://ceph_ai:{secrets['rabbitmq_password']}@rabbitmq:5672/",
        "SESSION_SECRET_KEY": secrets["session_secret"],
        "DASHBOARD_PASSWORD_HASH": secrets["dashboard_password_hash"],
        "AUTOPILOT_ENABLED": "false",
    })
    values.setdefault("DASHBOARD_USERNAME", "admin")
    for key, value in values.items():
        if key not in allowed:
            raise ValueError(f"{key} is not a setting of this image")
        if "\n" in value or "\r" in value:
            raise ValueError(f"{key} has a line break, which an env file cannot carry")
    return values, {name: sorted(keys) for name, keys in report.items()}


def write(path: Path, values: dict[str, str]) -> None:
    # Unquoted KEY=value lines: podman reads --env-file literally, so quotes would become part of a value.
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(f".{path.name}.tmp")
    with os.fdopen(os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o640), "w", encoding="utf-8") as handle:
        handle.write("# Generated by scripts/customer/build_env.py; secrets live only here.\n")
        for key in sorted(values):
            handle.write(f"{key}={values[key]}\n")
    os.replace(temporary, path)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", required=True, type=Path)
    parser.add_argument("--old-env", type=Path)
    args = parser.parse_args(argv)
    secrets = json.load(sys.stdin)
    old = dotenv_values(args.old_env) if args.old_env else {}
    try:
        values, report = build(old, secrets, allowed_keys())
    except ValueError as exc:
        print(f"build_env: {exc}", file=sys.stderr)
        return 2
    write(args.out, values)
    print(json.dumps(report, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
