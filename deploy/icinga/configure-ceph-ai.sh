#!/usr/bin/env bash
# Apply the Ceph checks and Ceph AI / Telegram notifications to an Icinga host (plan icinga I1).
#
#   sudo bash configure-ceph-ai.sh <dir with check_ceph_cluster, ceph-ai.conf, notify-*.sh>
#
# Clusters: one directory per cluster, /etc/icinga2/ceph/<NAME>/ with ceph.conf, keyring
# (client.icinga, read-only caps) and address (one MON address, for display). Settings:
# /etc/icinga2/ceph-ai/webhook.env (CEPH_AI_URL, CEPH_AI_TOKEN) and telegram.env
# (TELEGRAM_BOT_TOKEN, TELEGRAM_CHAT_ID), 0640 root:nagios; a missing file leaves that
# notification command failing in the Icinga log, nothing else.
set -euo pipefail
SRC="${1:?directory with the files from deploy/icinga}"
CEPH_DIR=/etc/icinga2/ceph
say() { printf '%s %s\n' "$(date '+%H:%M:%S')" "$*" >&2; }   # stderr: some calls sit inside a block written to a config file

install -m 0755 "$SRC/check_ceph_cluster" /usr/lib/nagios/plugins/check_ceph_cluster
install -d -m 0755 /etc/icinga2/scripts
install -m 0750 -g nagios "$SRC/notify-ceph-ai.sh" /etc/icinga2/scripts/notify-ceph-ai.sh
install -m 0750 -g nagios "$SRC/notify-telegram.sh" /etc/icinga2/scripts/notify-telegram.sh
install -d -m 0750 -g nagios /etc/icinga2/ceph-ai "$CEPH_DIR"
install -m 0644 "$SRC/ceph-ai.conf" /etc/icinga2/conf.d/ceph-ai.conf

say "clusters"
{
  echo "// Generated by deploy/icinga/configure-ceph-ai.sh from $CEPH_DIR/<name>/."
  for dir in "$CEPH_DIR"/*/; do
    dir="${dir%/}"
    [ -f "$dir/ceph.conf" ] && [ -f "$dir/keyring" ] || continue
    name="$(basename "$dir")"
    [[ "$name" =~ ^[A-Za-z0-9._-]+$ ]] || { echo "bad cluster name: $name" >&2; exit 1; }
    chgrp -R nagios "$dir"; chmod 0750 "$dir"; chmod 0640 "$dir"/*
    cat <<CONF
object Host "$name" {
  import "ceph-cluster"
  address = "$(cat "$dir/address" 2>/dev/null || echo 127.0.0.1)"
  vars.ceph_conf = "$dir/ceph.conf"
  vars.ceph_keyring = "$dir/keyring"
}
CONF
    say "  $name"
  done
} > /etc/icinga2/conf.d/ceph-clusters.conf

for file in webhook.env telegram.env; do
  [ ! -f "/etc/icinga2/ceph-ai/$file" ] || { chgrp nagios "/etc/icinga2/ceph-ai/$file"; chmod 0640 "/etc/icinga2/ceph-ai/$file"; }
done

say "validate and reload"
icinga2 daemon -C >/dev/null
systemctl reload icinga2
say "OK"
